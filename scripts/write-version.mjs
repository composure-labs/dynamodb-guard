#!/usr/bin/env node

/**
 * Writes src/core/version.ts from package.json's version. A dual ESM/CommonJS
 * build can't read package.json at runtime: `import.meta` has no CommonJS form,
 * and tshy writes its own package.json into each dist/ folder, so a relative
 * JSON import would find the wrong file.
 *
 * Run by `npm version`, as the `version` lifecycle script.
 */

import { readFileSync, writeFileSync } from "node:fs";

const { version } = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));

writeFileSync(
  new URL("../src/core/version.ts", import.meta.url),
  `// Generated by scripts/write-version.mjs; do not edit.

/** This package's version, as published. */
export const VERSION = ${JSON.stringify(version)};
`,
);
console.log(`src/core/version.ts: ${version}`);
