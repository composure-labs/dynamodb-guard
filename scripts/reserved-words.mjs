#!/usr/bin/env node

/**
 * Compares src/core/reserved-words.ts with the DynamoDB reserved-words page,
 * and with `--write` regenerates the file from it.
 *
 * Run by hand, now and then: it fetches over the network and parses AWS's
 * HTML, so it is no CI gate. AWS rarely changes the list, because a new
 * reserved word would break existing tables' queries. The file keeps only the
 * words, which are facts; none of the page's prose is copied.
 *
 * Usage: node scripts/reserved-words.mjs [--write]
 */

import { readFileSync, writeFileSync } from "node:fs";

const SOURCE =
  "https://docs.aws.amazon.com/amazondynamodb/latest/developerguide/ReservedWords.html";
const FILE = new URL("../src/core/reserved-words.ts", import.meta.url);

const response = await fetch(SOURCE);
if (!response.ok) {
  console.error(`✗ ${SOURCE} returned ${String(response.status)}`);
  process.exit(1);
}
const block = /<pre class="programlisting">([\s\S]*?)<\/pre>/.exec(await response.text())?.[1];
if (block === undefined) {
  console.error("✗ The page has no word list where it used to; check the page and this parser.");
  process.exit(1);
}
// Words are whitespace-separated runs of capitals and underscores. Matching
// only those, rather than stripping tags, keeps the page's markup (a copy
// button) out of the list and guarantees nothing else reaches src/.
const published = [...block.matchAll(/(?<=^|\s)[A-Z][A-Z_]*(?=\s|$)/g)]
  .map(([word]) => word)
  .sort();

const current =
  /`([\s\S]*?)`/.exec(readFileSync(FILE, "utf8"))?.[1].split(/\s+/).filter(Boolean) ?? [];
const added = published.filter((word) => !current.includes(word));
const removed = current.filter((word) => !published.includes(word));

if (process.argv.includes("--write")) {
  const lines = [];
  for (let i = 0; i < published.length; i += 8) lines.push(published.slice(i, i + 8).join(" "));
  writeFileSync(
    FILE,
    `// Generated by scripts/reserved-words.mjs from
// ${SOURCE}
// (${new Date().toISOString().slice(0, 10)}). Regenerate rather than edit.

const WORDS = \`
${lines.join("\n")}
\`;

/**
 * DynamoDB's reserved words, upper-cased. An expression that names one
 * without an \`ExpressionAttributeNames\` alias is rejected, in any letter case.
 */
export const RESERVED_WORDS: ReadonlySet<string> = new Set(WORDS.split(/\\s+/).filter(Boolean));

/** Whether DynamoDB reserves \`word\`, in any letter case. */
export const isReservedWord = (word: string): boolean => RESERVED_WORDS.has(word.toUpperCase());
`,
  );
  console.log(`✓ Wrote ${String(published.length)} words to src/core/reserved-words.ts.`);
} else if (added.length > 0 || removed.length > 0) {
  console.error(
    `✗ The list differs from the page. Added: ${added.join(", ") || "none"}. Removed: ${removed.join(", ") || "none"}.`,
  );
  console.error("  Run with --write to regenerate.");
  process.exit(1);
} else {
  console.log(`✓ ${String(current.length)} words, matching the page.`);
}
